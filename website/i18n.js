  function detect() {
    // explicit ?lang=xx wins (shareable localized links)
    try {
      var q = new URLSearchParams(location.search).get('lang');
      if (q && SUPPORTED.indexOf(q) !== -1) return q;
    } catch (e) {}
    try {
      var saved = localStorage.getItem('mb_lang');
      if (saved && SUPPORTED.indexOf(saved) !== -1) return saved;
    } catch (e) {}
    var navs = navigator.languages || [navigator.language || 'en'];
    for (var i = 0; i < navs.length; i++) {
      var p = String(navs[i]).toLowerCase().split('-')[0];
      if (SUPPORTED.indexOf(p) !== -1) return p;
    }
    return 'en';
  }

